def _block(text: str, indent: int = 6) -> str:
    """Render ``text`` as the body of a YAML literal block (``|``, clip chomping)."""
    if not text.endswith("\n") or text.endswith("\n\n"):
        raise ValueError("expected exactly one trailing newline (YAML '|' clip chomping)")
    pad = " " * indent
    return "\n".join(pad + line if line else "" for line in text.rstrip("\n").split("\n")) + "\n"


def _render(*, title: str, extra: str, requires: str, path: str, code_env: str, low_level: str,
            low_level_args: str, output_dir: str, prompts: dict[str, str]) -> str:
    run = f"uv run --no-sync --active capx/envs/launch.py --config-path {path} --model <MODEL> ..."
    return HEADER.format(title=title, extra=extra, requires=requires, run=run) + BODY.format(
        code_env=code_env,
        low_level=low_level,
        low_level_args=low_level_args,
        prompt=_block(prompts["prompt"]),
        multi_turn_prompt=_block(prompts["multi_turn_prompt"]),
        output_dir=output_dir,
    )


def build() -> dict[Path, str]:
    cfg = yaml.safe_load(CAP_AGENT0_CONFIG.read_text())["env"]["cfg"]
    prompts = {"prompt": cfg["prompt"], "multi_turn_prompt": cfg["multi_turn_prompt"]}
    ll = cfg["low_level"]
    files: dict[Path, str] = {}

    rel = Path("libero_pro") / f"franka_{ll['suite_name']}_{ll['task_id']}.yaml"
    files[rel] = _render(
        title=f"LIBERO-PRO {ll['suite_name']} task {ll['task_id']}",
        extra="--extra libero",
        requires="uv sync --active --extra libero --extra contactgraspnet (.venv-libero)",
        path=f"env_configs/capbg_baseline/{rel.as_posix()}",
        code_env="capx.envs.tasks.franka.franka_libero_env.FrankaLiberoCodeEnv",
        low_level="capx.envs.simulators.libero.FrankaLiberoEnv",
        low_level_args=f"      suite_name: {ll['suite_name']}\n      task_id: {ll['task_id']}\n",
        output_dir=f"./outputs/capbg_baseline/libero_pro/{ll['suite_name']}_{ll['task_id']}",
        prompts=prompts,
    )

    for task_id, (slug, upstream_name) in enumerate(LIBERO_MEM_TASKS):
        stem = f"task_{task_id:02d}_{slug}"
        rel = Path("libero_mem") / f"{stem}.yaml"
        files[rel] = _render(
            title=f"LIBERO-Mem task {task_id} ({upstream_name})",
            extra="--extra libero-mem",
            requires="uv sync --active --extra libero-mem --extra contactgraspnet (.venv-libero-mem); "
            "GPU: MUJOCO_GL=egl PYOPENGL_PLATFORM=egl; CPU only: MUJOCO_GL=osmesa PYOPENGL_PLATFORM=osmesa "
            "NUMBA_DISABLE_JIT=1",
            path=f"env_configs/capbg_baseline/{rel.as_posix()}",
            code_env="capx.envs.tasks.franka.franka_libero_mem_env.FrankaLiberoMemCodeEnv",
            low_level="capx.envs.simulators.libero_mem.FrankaLiberoMemEnv",
            low_level_args=f"      task_id: {task_id}\n",
            output_dir=f"./outputs/capbg_baseline/libero_mem/{stem}",
            prompts=prompts,
        )
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that generated files are up to date")
    args = parser.parse_args()

    files = build()
    expected = {OUT_ROOT / rel for rel in files}
    stale = [p for p in OUT_ROOT.rglob("*.yaml") if p not in expected] if OUT_ROOT.exists() else []
    changed = [OUT_ROOT / rel for rel, text in files.items()
               if not (OUT_ROOT / rel).exists() or (OUT_ROOT / rel).read_text() != text]

    if args.check:
        for p in changed:
            print(f"out of date: {p.relative_to(REPO_ROOT)}")
        for p in stale:
            print(f"not generated by this script: {p.relative_to(REPO_ROOT)}")
        return 1 if changed or stale else 0

    for p in stale:
        p.unlink()
        print(f"removed {p.relative_to(REPO_ROOT)}")
    for rel, text in files.items():
        path = OUT_ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(files)} configs under {OUT_ROOT.relative_to(REPO_ROOT)} ({len(changed)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
