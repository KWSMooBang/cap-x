"""Generate the cap-bg baseline env configs from one template.

Baseline = CaP-Agent0 settings (env_configs/libero/franka_libero_cap_agent0.yaml) with the
parallel ensemble turned off. ``prompt`` and ``multi_turn_prompt`` are copied from that file
verbatim, so the two can't drift apart.

Usage::

    python scripts/gen_capbg_baseline_configs.py          # (re)write env_configs/capbg_baseline/
    python scripts/gen_capbg_baseline_configs.py --check  # exit 1 if any file is stale

Do not edit the generated YAMLs by hand; change this script and rerun it.
"""

