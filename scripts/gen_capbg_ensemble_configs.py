"""Generate the Nebius ensemble pilot configs (env_configs/capbg_ensemble/{libero_mem,libero_pro,robomme}/).

Each file is the matching baseline config (env_configs/capbg_baseline/{libero_mem,libero_pro}/ or env_configs/robomme/) with
only these changes: the header, ``use_parallel_ensemble`` / ``use_multimodel`` on, the ``ensemble`` block
(candidates x temperatures and the synthesis model), ``condition_video_mode: auto`` (RoboMME) and
``output_dir`` under ./outputs/capbg_ensemble/. Prompts, APIs, servers, VDM, budgets and the rest are the
baseline's, byte for byte.

Usage::

    python scripts/gen_capbg_ensemble_configs.py          # (re)write env_configs/capbg_ensemble/
    python scripts/gen_capbg_ensemble_configs.py --check  # exit 1 if any file is stale
    # swap a candidate (keeps its temperatures) or set the whole list / the synthesis model:
    python scripts/gen_capbg_ensemble_configs.py --replace deepseek-ai/DeepSeek-V4-Flash-0731=zai-org/GLM-5.3
    python scripts/gen_capbg_ensemble_configs.py --candidates "a/m1@0.1,0.5,0.9;b/m2@0.1,0.5,0.9" --synthesis-model c/m3
    # RoboMME: another model describes the conditioning video of some tasks (here one call with 32 frames):
    python scripts/gen_capbg_ensemble_configs.py --condition-video-model moonshotai/Kimi-K3 \\
        --condition-video-tasks VideoUnmaskSwap,VideoPlaceOrder,MoveCube,PatternLock \\
        --condition-video-segment-frames 0 --condition-frames 32
    python scripts/gen_capbg_ensemble_configs.py --condition-video-model none  # back to the turn VDM

The model choice (and the conditioning-video override) is stored in env_configs/capbg_ensemble/models.json (written whenever it changes), so later runs
and ``--check`` use the same models without repeating the arguments.

Do not edit the generated YAMLs by hand; change this script (or the baseline generators) and rerun it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))  # capx (text-only model list, candidate parser)
sys.path.insert(0, str(REPO_ROOT / "scripts"))
from gen_capbg_baseline_configs import LIBERO_PRO_SUITES, libero_pro_tasks  # noqa: E402,F401
OUT_ROOT = REPO_ROOT / "env_configs" / "capbg_ensemble"
BASELINE_LIBERO_MEM = REPO_ROOT / "env_configs" / "capbg_baseline" / "libero_mem"
BASELINE_LIBERO_PRO = REPO_ROOT / "env_configs" / "capbg_baseline" / "libero_pro"
BASELINE_ROBOMME = REPO_ROOT / "env_configs" / "robomme"

# Pilot tasks (lead, 2026-11-01); LIBERO-Mem extended to all 10 tasks (2026-11-02).
LIBERO_MEM_TASKS = list(range(10))
ROBOMME_TASKS = ["PickXtimes", "StopCube", "VideoUnmaskSwap", "ButtonUnmask", "PickHighlight", "VideoPlaceOrder",
                 "MoveCube", "PatternLock"]

# First pilot choice (lead, 2026-11-01); models.json overrides it once written.
DEFAULT_CANDIDATES = [
    ("openai/gpt-oss-120b", [0.1, 0.5, 0.9]),
    ("Qwen/Qwen3-235B-A22B-Instruct-2507", [0.1, 0.5, 0.9]),
    ("moonshotai/Kimi-K2.7-Code", [0.1, 0.5, 0.9]),
]
DEFAULT_SYNTHESIS_MODEL = "deepseek-ai/DeepSeek-V4-Pro"
VDM_MODEL = "Qwen/Qwen3.8-27B"
MODELS_FILE = OUT_ROOT / "models.json"
# vdm_text segmentation written into the RoboMME configs (capx.envs.tasks.robomme.robomme_env defaults).
CONDITION_VIDEO_SEGMENTS = {"stride": 1, "segment_frames": 20, "overlap": 4, "max_segments": 12}
# RoboMME pilot tasks with a conditioning video (Video* and the imitation tasks).
CONDITION_VIDEO_TASKS = ["VideoUnmaskSwap", "VideoPlaceOrder", "MoveCube", "PatternLock"]


def load_models(path: Path = MODELS_FILE) -> tuple[list[tuple[str, list[float]]], str]:
    """(candidates, synthesis model) from models.json, else the defaults."""
    if path.exists():
        data = json.loads(path.read_text())
        return [(m, [float(t) for t in ts]) for m, ts in data["candidates"]], data["synthesis_model"]
    return [(m, list(ts)) for m, ts in DEFAULT_CANDIDATES], DEFAULT_SYNTHESIS_MODEL


def load_condition_video(path: Path = MODELS_FILE) -> dict | None:
    """models.json's conditioning-video override ``{model, tasks, segment_frames, condition_frames}`` or None
    (then the turn VDM describes every RoboMME conditioning video with CONDITION_VIDEO_SEGMENTS)."""
    if path.exists():
        return json.loads(path.read_text()).get("condition_video")
    return None


def models_json(candidates: list[tuple[str, list[float]]], synthesis: str, condition_video: dict | None = None) -> str:
    rows = ",\n".join(f"    {json.dumps([m, ts])}" for m, ts in candidates)
    cv = f',\n  "condition_video": {json.dumps(condition_video)}' if condition_video else ""
    return f'{{\n  "candidates": [\n{rows}\n  ],\n  "synthesis_model": {json.dumps(synthesis)}{cv}\n}}\n'


CANDIDATES, SYNTHESIS_MODEL = load_models()
CONDITION_VIDEO = load_condition_video()

HEADER = """\
# GENERATED by scripts/gen_capbg_ensemble_configs.py -- do not edit by hand.
# cap-bg Nebius ensemble pilot: {title}
# = {baseline} with the multimodel parallel ensemble ON:
#   candidates {cand_names} ({n_replies} replies per query),
#   synthesis {synth_name} (upstream synthesis prompt). {text_only}{cv_note}
# Everything else (prompts, APIs, servers, VDM on, video, max_tokens, budgets) is the baseline's.
# VDM: --visual-differencing-model {vdm} (as the baseline). Molmo2-8B server at 127.0.0.1:8122 as for the baseline.
# Requires the baseline venv ({venv}). Run: python scripts/run_ensemble_pilot.py --bench {bench} ...  (docs/capbg-ensemble.md)
"""

CV_NOTE = (
    "\n# condition_video_mode auto -> vdm_text (if a coding-side model is text-only): the VDM describes the"
    "\n# conditioning video part by part (condition_video_* keys) and the text replaces the images in the first prompt."
)

ENSEMBLE_KEYS = """\
use_parallel_ensemble: true
use_multimodel: true
# Multimodel ensemble: every (model, temperature) is one candidate reply; failed candidates are left out.
ensemble:
  candidates:
{candidates}
  synthesis_model: {synthesis}
"""


def _ensemble_block(robomme: bool, candidates: list[tuple[str, list[float]]], synthesis: str,
                    cv: dict | None = None) -> str:
    cands = "\n".join(
        f"    - model: {m}\n      temperatures: [{', '.join(f'{t:g}' for t in temps)}]" for m, temps in candidates
    )
    block = ENSEMBLE_KEYS.format(candidates=cands, synthesis=synthesis)
    if robomme:
        block += ("# Conditioning video: images | vdm_text | auto (auto = vdm_text when a coding-side model is "
                  "text-only).\ncondition_video_mode: auto\n"
                  "# vdm_text: every stride-th frame, segment_frames per VDM call, overlap frames shared with the "
                  "previous call,\n# at most max_segments calls (the stride grows if needed).\n")
        segments = dict(CONDITION_VIDEO_SEGMENTS)
        if cv is not None and cv.get("segment_frames") is not None:
            segments["segment_frames"] = int(cv["segment_frames"])
        if segments["segment_frames"] == 0:
            block += ("# segment_frames 0: one call with the condition_frames sampled frames (stride / overlap / "
                      "max_segments unused).\n")
        block += "".join(f"condition_video_{k}: {v}\n" for k, v in segments.items())
        if cv is not None:
            block += ("# Model that describes the conditioning video (turn VDM calls keep the VDM model).\n"
                      f"condition_video_model: {cv['model']}\n")
    return block


def _header_fields(candidates: list[tuple[str, list[float]]], synthesis: str) -> dict[str, str]:
    from capx.llm.client import is_text_only_model

    def short(m: str) -> str:
        return m.split("/")[-1]

    temps = {tuple(ts) for _, ts in candidates}
    names = " / ".join(short(m) for m, _ in candidates)
    if len(temps) == 1:
        names += " x temperatures " + ", ".join(f"{t:g}" for t in next(iter(temps)))
    models = [m for m, _ in candidates] + [synthesis]
    text_only = [m for m in models if is_text_only_model(m)]
    if len(text_only) == len(models):
        note = "All coding-side models are text-only."
    elif text_only:
        note = "Text-only: " + ", ".join(short(m) for m in text_only) + "."
    else:
        note = "No coding-side model is listed as text-only."
    return {"cand_names": names, "n_replies": str(sum(len(ts) for _, ts in candidates)),
            "synth_name": short(synthesis), "text_only": note}


def _strip_header(text: str) -> str:
    lines = text.split("\n")
    i = 0
    while i < len(lines) and lines[i].startswith("#"):
        i += 1
    return "\n".join(lines[i:])


def _convert(text: str, *, robomme: bool, title: str, baseline: str, bench: str, out_old: str, out_new: str,
             venv: str, candidates: list[tuple[str, list[float]]], synthesis: str, cv: dict | None = None) -> str:
    body = _strip_header(text)
    off = "use_parallel_ensemble: false\nuse_multimodel: false\n"
    if body.count(off) != 1:
        raise ValueError(f"{baseline}: expected one '{off!r}' block")
    body = body.replace(off, _ensemble_block(robomme, candidates, synthesis, cv))
    if body.count(out_old) != 1:
        raise ValueError(f"{baseline}: expected output_dir {out_old!r}")
    body = body.replace(out_old, out_new)
    if cv is not None and cv.get("condition_frames") is not None:
        frames = "      condition_frames: 32\n"
        if body.count(frames) != 1:
            raise ValueError(f"{baseline}: expected one {frames!r}")
        body = body.replace(frames, f"      condition_frames: {int(cv['condition_frames'])}\n")
    cv_note = CV_NOTE if robomme else ""
    if cv is not None:
        how = "in one call" if cv.get("segment_frames") == 0 else "in parts"
        frames_note = f", condition_frames {cv['condition_frames']}" if cv.get("condition_frames") is not None else ""
        cv_note += (f"\n# Here the conditioning video is described by {cv['model']} (condition_video_model), "
                    f"{how}{frames_note}; turn VDM calls keep {VDM_MODEL}.")
    header = HEADER.format(title=title, baseline=baseline, vdm=VDM_MODEL, bench=bench, venv=venv,
                           cv_note=cv_note, **_header_fields(candidates, synthesis))
    return header + body


_FROM_MODELS_FILE = object()


def build(candidates: list[tuple[str, list[float]]] | None = None, synthesis: str | None = None,
          condition_video: Any = _FROM_MODELS_FILE) -> dict[Path, str]:
    """``condition_video``: default models.json's override, None for none."""
    candidates = candidates if candidates is not None else CANDIDATES
    synthesis = synthesis or SYNTHESIS_MODEL
    cv_all = CONDITION_VIDEO if condition_video is _FROM_MODELS_FILE else condition_video
    files: dict[Path, str] = {}
    for idx in LIBERO_MEM_TASKS:
        (src,) = sorted(BASELINE_LIBERO_MEM.glob(f"task_{idx:02d}_*.yaml"))
        rel = src.relative_to(REPO_ROOT).as_posix()
        files[Path("libero_mem") / src.name] = _convert(
            src.read_text(), robomme=False, title=f"LIBERO-Mem task {idx} ({src.stem})", baseline=rel,
            bench="libero_mem", venv=".venv-libero-mem",
            out_old=f"output_dir: ./outputs/capbg_baseline/libero_mem/{src.stem}",
            out_new=f"output_dir: ./outputs/capbg_ensemble/libero_mem/{src.stem}",
            candidates=candidates, synthesis=synthesis,
        )
    for suite, idx in libero_pro_tasks():
        src = BASELINE_LIBERO_PRO / f"franka_{suite}_{idx}.yaml"
        rel = src.relative_to(REPO_ROOT).as_posix()
        files[Path("libero_pro") / src.name] = _convert(
            src.read_text(), robomme=False, title=f"LIBERO-PRO {suite} task {idx} (trial k = init state k-1)",
            baseline=rel, bench="libero_pro", venv=".venv-libero",
            out_old=f"output_dir: ./outputs/capbg_baseline/libero_pro/{suite}_{idx}",
            out_new=f"output_dir: ./outputs/capbg_ensemble/libero_pro/{suite}_{idx}",
            candidates=candidates, synthesis=synthesis,
        )
    for task in ROBOMME_TASKS:
        stem = f"robomme_{task.lower()}"
        src = BASELINE_ROBOMME / f"{stem}.yaml"
        rel = src.relative_to(REPO_ROOT).as_posix()
        files[Path("robomme") / src.name] = _convert(
            src.read_text(), robomme=True, title=f"RoboMME {task} (trial k = test episode k-1)", baseline=rel,
            bench="robomme", venv=".venv-robomme",
            out_old=f"output_dir: ./outputs/robomme/{stem}",
            out_new=f"output_dir: ./outputs/capbg_ensemble/robomme/{stem}",
            candidates=candidates, synthesis=synthesis,
            cv=cv_all if cv_all is not None and task in cv_all["tasks"] else None,
        )
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that generated files are up to date")
    parser.add_argument("--candidates", default=None,
                        help='candidate list "model@t1,t2,...;model2@..." (default: models.json or the pilot choice)')
    parser.add_argument("--replace", action="append", default=[], metavar="OLD=NEW",
                        help="replace candidate OLD by NEW with the same temperatures (repeatable)")
    parser.add_argument("--synthesis-model", default=None, help="synthesis model (default: models.json)")
    parser.add_argument("--condition-video-model", default=None,
                        help="RoboMME: model that describes the conditioning video of --condition-video-tasks "
                             "(must take images); 'none' removes the override (default: models.json)")
    parser.add_argument("--condition-video-tasks", default=None,
                        help=f"comma-separated RoboMME tasks for --condition-video-model (default: "
                             f"{','.join(CONDITION_VIDEO_TASKS)})")
    parser.add_argument("--condition-video-segment-frames", type=int, default=None,
                        help="condition_video_segment_frames for those tasks (0 = one call with the sampled frames)")
    parser.add_argument("--condition-frames", type=int, default=None,
                        help="condition_frames (sampled conditioning frames) for those tasks")
    args = parser.parse_args()

    from capx.llm.client import parse_ensemble_candidates

    candidates = parse_ensemble_candidates(args.candidates) if args.candidates else list(CANDIDATES)
    for item in args.replace:
        old, sep, new = item.partition("=")
        if not sep or old not in [m for m, _ in candidates]:
            parser.error(f"--replace {item!r}: expected OLD=NEW with OLD one of {[m for m, _ in candidates]}")
        candidates = [(new if m == old else m, ts) for m, ts in candidates]
    synthesis = args.synthesis_model or SYNTHESIS_MODEL
    cv = CONDITION_VIDEO
    if args.condition_video_model == "none":
        cv = None
    elif args.condition_video_model is not None:
        from capx.llm.client import check_condition_video_model

        try:
            check_condition_video_model(args.condition_video_model)
        except ValueError as exc:
            parser.error(str(exc))
        tasks = args.condition_video_tasks.split(",") if args.condition_video_tasks else CONDITION_VIDEO_TASKS
        bad = [t for t in tasks if t not in ROBOMME_TASKS]
        if bad:
            parser.error(f"--condition-video-tasks: unknown {bad} (one of {ROBOMME_TASKS})")
        if args.condition_video_segment_frames is not None and args.condition_video_segment_frames < 0:
            parser.error("--condition-video-segment-frames must be >= 0")
        if args.condition_frames is not None and args.condition_frames < 1:
            parser.error("--condition-frames must be >= 1")
        cv = {"model": args.condition_video_model, "tasks": [t for t in ROBOMME_TASKS if t in tasks],
              "segment_frames": args.condition_video_segment_frames, "condition_frames": args.condition_frames}
    elif any(v is not None for v in (args.condition_video_tasks, args.condition_video_segment_frames,
                                     args.condition_frames)):
        parser.error("--condition-video-tasks / --condition-video-segment-frames / --condition-frames need "
                     "--condition-video-model")
    models_text = models_json(candidates, synthesis, cv)

    files = build(candidates, synthesis, cv)
    expected = {OUT_ROOT / rel for rel in files}
    stale = [p for p in OUT_ROOT.rglob("*.yaml") if p not in expected] if OUT_ROOT.exists() else []
    changed = [OUT_ROOT / rel for rel, text in files.items()
               if not (OUT_ROOT / rel).exists() or (OUT_ROOT / rel).read_text() != text]
    models_changed = not MODELS_FILE.exists() or MODELS_FILE.read_text() != models_text
    if models_changed:
        changed.append(MODELS_FILE)
    if args.check:
        for p in changed:
            print(f"out of date: {p.relative_to(REPO_ROOT)}")
        for p in stale:
            print(f"not generated by this script: {p.relative_to(REPO_ROOT)}")
        return 1 if changed or stale else 0
    for p in stale:
        p.unlink()
        print(f"removed {p.relative_to(REPO_ROOT)}")
    for rel, text in files.items():
        (OUT_ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
        (OUT_ROOT / rel).write_text(text)
    if models_changed:
        MODELS_FILE.write_text(models_text)
    print("candidates: " + "; ".join(f"{m} @ {ts}" for m, ts in candidates) + f"; synthesis: {synthesis}")
    if cv is not None:
        print(f"condition video: {cv['model']} for {', '.join(cv['tasks'])} "
              f"(segment_frames {cv['segment_frames']}, condition_frames {cv['condition_frames']})")
    print(f"wrote {len(files)} configs under {OUT_ROOT.relative_to(REPO_ROOT)} ({len(changed)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
