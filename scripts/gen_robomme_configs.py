"""Generate the 16 RoboMME CaP-X baseline configs (env_configs/robomme/robomme_<task>.yaml).

Same settings as the cap-bg LIBERO-Mem baseline (scripts/gen_capbg_baseline_configs.py): CaP-Agent0 prompts
copied verbatim from env_configs/libero/franka_libero_cap_agent0.yaml, the same API servers, parallel ensemble
off, image differencing on, video recording on, max_tokens 32768, memory_mode none. RoboMME-specific:
``FrankaRoboMMEApiReducedSkillLibrary`` (same functions as FrankaLiberoApiReducedSkillLibrary), RoboMME's
1300-step budget, a 3600 s wall-clock budget per trial (one attempt) and 32 conditioning-video frames
(MME-VLA framesamp-modul: 512-token memory / 16 tokens per frame = 32 frames).

Usage::

    python scripts/gen_robomme_configs.py          # (re)write env_configs/robomme/
    python scripts/gen_robomme_configs.py --check  # exit 1 if any file is stale

Do not edit the generated YAMLs by hand; change this script and rerun it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_capbg_baseline_configs import CAP_AGENT0_CONFIG, REPO_ROOT, _block  # noqa: E402

OUT_ROOT = REPO_ROOT / "env_configs" / "robomme"

# BenchmarkEnvBuilder.get_task_list() order, with the suite of each task (RoboMME README).
TASKS = [
    ("PickXtimes", "Counting"), ("StopCube", "Counting"), ("SwingXtimes", "Counting"), ("BinFill", "Counting"),
    ("VideoUnmaskSwap", "Permanence"), ("VideoUnmask", "Permanence"), ("ButtonUnmaskSwap", "Permanence"),
    ("ButtonUnmask", "Permanence"), ("VideoRepick", "Reference"), ("VideoPlaceButton", "Reference"),
    ("VideoPlaceOrder", "Reference"), ("PickHighlight", "Reference"), ("InsertPeg", "Imitation"),
    ("MoveCube", "Imitation"), ("PatternLock", "Imitation"), ("RouteStick", "Imitation"),
]
# Tasks whose reset returns a conditioning video (tasks with "demonstration": True subtasks).
VIDEO_TASKS = {"VideoUnmaskSwap", "VideoUnmask", "VideoRepick", "VideoPlaceButton", "VideoPlaceOrder",
               "InsertPeg", "MoveCube", "PatternLock", "RouteStick"}
STICK_TASKS = {"PatternLock", "RouteStick"}

HEADER = """\
# GENERATED by scripts/gen_robomme_configs.py -- do not edit by hand.
# RoboMME {task} ({suite} suite), test split. CaP-X baseline (memory_mode none) with the cap-bg LIBERO-Mem
# baseline settings: CaP-Agent0 prompts, FrankaRoboMMEApiReducedSkillLibrary (same functions as
# FrankaLiberoApiReducedSkillLibrary), parallel ensemble OFF, VDM on, video on, max_tokens 32768.
# {notes}
# Trial k plays test episode k-1 (fixed). Budget: 1300 control steps (RoboMME paper), 3600 s wall clock, one attempt.
# Molmo (point_prompt_molmo) needs a separate Molmo2-8B vLLM server at 127.0.0.1:8122 (see docs/capbg-baseline.md).
#
# Requires: uv sync --active --extra robomme --extra contactgraspnet (.venv-robomme, Python >= 3.11) and an NVIDIA Vulkan ICD.
# Run: python capx/envs/launch.py --config-path env_configs/robomme/{stem}.yaml \\
#        --model moonshotai/Kimi-K3 --visual-differencing-model Qwen/Qwen3.8-27B ...  (see docs/memory-benchmarks.md)
"""

BODY = """\

env:
  _target_: capx.envs.tasks.robomme.robomme_env.RoboMMECodeEnv
  cfg:
    _target_: capx.envs.tasks.base.CodeExecEnvConfig
    low_level:
      _target_: capx.envs.simulators.robomme.RoboMMEEnv
      task_id: {task}
      episode_idx: 0
      dataset: test
      privileged: false
      max_steps: 1300
      condition_frames: 32
    privileged: false
    apis:
      - FrankaRoboMMEApiReducedSkillLibrary
    prompt: |
{prompt}
    multi_turn_prompt: |
{multi_turn_prompt}
api_servers:
{api_servers}
memory_mode: none
use_parallel_ensemble: false
use_multimodel: false
use_img_differencing: true
use_visual_feedback: false
use_video_differencing: false
use_wrist_camera: false
record_video: true
save_multiturn_prompts: true
# Per-reply token limit for the coding model and the VDM (CLI --max-tokens overrides); as the LIBERO-Mem baseline.
max_tokens: 32768
trial_timeout_s: 3600
max_trial_retries: 1
output_dir: ./outputs/robomme/{stem}

trials: 50
num_workers: 1
"""


def _notes(task: str) -> str:
    notes = []
    if task in VIDEO_TASKS:
        notes.append("Reset returns a conditioning video: 32 uniformly sampled front-camera frames go into the first prompt"
                     "\n# (as MME-VLA framesamp-modul: 512 tokens / 16 per frame). "
                     "Fallback if the model limits images: CAPX_ROBOMME_CONDITION_FRAMES=16.")
    else:
        notes.append("No conditioning video at reset.")
    if task in STICK_TASKS:
        notes.append("The robot holds a stick (no gripper): open/close_gripper do nothing.")
    return " ".join(notes)


def build() -> dict[Path, str]:
    cap_agent0 = yaml.safe_load(CAP_AGENT0_CONFIG.read_text())
    cfg = cap_agent0["env"]["cfg"]
    api_servers = yaml.safe_dump(cap_agent0["api_servers"], sort_keys=False, default_flow_style=False)
    api_servers = "\n".join("  " + ln if ln else "" for ln in api_servers.rstrip("\n").split("\n"))
    files: dict[Path, str] = {}
    for task, suite in TASKS:
        stem = f"robomme_{task.lower()}"
        files[Path(f"{stem}.yaml")] = HEADER.format(
            task=task, suite=suite, notes=_notes(task), stem=stem
        ) + BODY.format(
            task=task,
            prompt=_block(cfg["prompt"]),
            multi_turn_prompt=_block(cfg["multi_turn_prompt"]),
            api_servers=api_servers,
            stem=stem,
        )
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that generated files are up to date")
    args = parser.parse_args()

    files = build()
    expected = {OUT_ROOT / rel for rel in files}
    stale = [p for p in OUT_ROOT.glob("*.yaml") if p not in expected] if OUT_ROOT.exists() else []
    changed = [OUT_ROOT / rel for rel, text in files.items()
               if not (OUT_ROOT / rel).exists() or (OUT_ROOT / rel).read_text() != text]
    if args.check:
        for p in changed:
            print(f"out of date: {p.relative_to(REPO_ROOT)}")
        for p in stale:
            print(f"not generated by this script: {p.relative_to(REPO_ROOT)}")
        return 1 if changed or stale else 0
    for p in stale:
        p.unlink()
        print(f"removed {p.relative_to(REPO_ROOT)}")
    OUT_ROOT.mkdir(parents=True, exist_ok=True)
    for rel, text in files.items():
        (OUT_ROOT / rel).write_text(text)
    print(f"wrote {len(files)} configs under {OUT_ROOT.relative_to(REPO_ROOT)} ({len(changed)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
